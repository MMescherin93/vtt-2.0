/*
 * Поля листа «Запретных земель».
 * Координаты — в пикселях фона 1200×1694 (две страницы PDF).
 * page: 0 — лицевая сторона, 1 — оборот.
 */
const text = (page, name, x, y, w, h, multiline = false) => ({
  page,
  name,
  kind: multiline ? 'area' : 'text',
  x,
  y,
  w,
  h
})
const num = (page, name, x, y, w, h) => ({ page, name, kind: 'number', x, y, w, h })
const check = (page, name, x, y, w = 24, h = 24) => ({
  page,
  name,
  kind: 'checkbox',
  x,
  y,
  w,
  h
})
const track = (page, name, x, y, w, h, max) => ({
  page,
  name,
  kind: 'track',
  x,
  y,
  w,
  h,
  max
})

